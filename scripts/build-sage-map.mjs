#!/usr/bin/env node
// One SAGE map for Galia and Mini-Sim (IDEA-014).
// Galia (src/data) is the source of truth; this writes the plain-JS copy the
// WordPress Mini-Sim loads, and copies the three CSS planet textures.
//   node --experimental-strip-types scripts/build-sage-map.mjs        write
//   node --experimental-strip-types scripts/build-sage-map.mjs --check fail if out of date
import { readFile, writeFile, copyFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const OUT = resolve(root, "mini-sim/assets/js/sage-map.js");
const TEXTURE_DIR = resolve(root, "mini-sim/assets/sage");

const sage = await import(pathToFileURL(resolve(root, "src/data/sage-plane.ts")).href);
const systems = await import(pathToFileURL(resolve(root, "src/data/systems.ts")).href);

// Galia's star palette lives in the canvas component; keep it in one place here.
const component = await readFile(resolve(root, "src/components/cartograph/sage-plane.tsx"), "utf8");
const palette = JSON.parse((component.match(/const KIND_COLOR = (\[[^\]]+\]);/) || [])[1] || "null");
if (!Array.isArray(palette) || palette.length !== 5) throw new Error("KIND_COLOR not found in sage-plane.tsx");

const CSS_SYSTEM = { oni: "oni", mud: "mud", ustur: "ustur" };
const textureFile = (path) => String(path || "").split("/").pop();

const data = {
  source: "Galia src/data/sage-plane.ts + systems.ts",
  range: sage.SAGE_RANGE,
  sectorCount: sage.SAGE_SECTOR_COUNT,
  kindColor: palette,
  factionTone: systems.FACTION_TONE,
  stars: sage.SAGE_STARS.map((s) => [s.x, s.y, s.kind, s.size, s.name]),
  css: sage.SAGE_CSS.map((c) => ({ id: c.id, faction: c.faction, name: c.name, x: c.x, y: c.y, system: CSS_SYSTEM[c.id] || null })),
  landmarks: sage.SAGE_LANDMARKS.map((mark) => ({ id: mark.id, x: mark.x, y: mark.y, name: mark.name, planet: mark.planet, color: mark.color })),
  systems: systems.SYSTEMS
    .filter((s) => Object.values(CSS_SYSTEM).includes(s.id))
    .map((s) => ({
      id: s.id,
      name: s.name,
      planet: s.planet,
      faction: s.faction,
      atmosphere: s.atmosphere,
      sun: s.sun,
      lore: s.lore,
      texture: "sage/" + textureFile(s.texture),
      markers: s.markers.map((m) => ({ id: m.id, name: m.name, kind: m.kind, placement: m.placement, blurb: m.blurb }))
    }))
};

const body = `/* GENERATED by scripts/build-sage-map.mjs from Galia src/data — do not edit by hand.
   One SAGE map for Galia and Mini-Sim (IDEA-014). */
window.BCMSageMap = ${JSON.stringify(data, null, 1)};
`;

if (process.argv.includes("--check")) {
  const current = await readFile(OUT, "utf8").catch(() => "");
  if (current.replace(/\r\n/g, "\n") !== body) {
    console.error("mini-sim/assets/js/sage-map.js is out of date: run node --experimental-strip-types scripts/build-sage-map.mjs");
    process.exit(1);
  }
  console.log("sage-map.js is in sync with Galia");
} else {
  await writeFile(OUT, body);
  await mkdir(TEXTURE_DIR, { recursive: true });
  for (const s of data.systems) {
    await copyFile(resolve(root, "public/textures", textureFile(s.texture)), resolve(TEXTURE_DIR, textureFile(s.texture)));
  }
  console.log(`wrote ${OUT} (${data.stars.length} stars, ${data.css.length} CSS, ${data.systems.length} systems)`);
}
