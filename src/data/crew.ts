export const APTITUDES = [
  "Command",
  "Flight",
  "Operator",
  "Engineering",
  "Medical",
  "Science",
  "Fitness",
  "Hospitality",
] as const;

export type Aptitude = (typeof APTITUDES)[number];

export const OFFICIAL = ["Common", "Uncommon", "Rare", "Epic", "Legendary", "Anomaly"] as const;
export type OfficialRarity = (typeof OFFICIAL)[number];

export const TENSOR_TIERS = ["anomaly", "legendary", "epic", "rare", "uncommon", "common"] as const;
export type TensorTier = (typeof TENSOR_TIERS)[number];

export const SPECIES = [
  "Ustur",
  "High Punaab",
  "Profound Punaab",
  "Sogmian",
  "Human",
  "Mierese",
] as const;
export type Species = (typeof SPECIES)[number];

export type AptitudeSlot = { name: Aptitude; xp: 50 | 25 };

export type Crew = {
  id: string;
  given: string;
  family: string;
  species: Species;
  sex: "Female" | "Male" | "Body 1" | "Body 2";
  official: OfficialRarity;
  tensorRank: number | null;
  aptitudes: AptitudeSlot[];
  o: number;
  c: number;
  e: number;
  a: number;
  n: number;
  university?: string;
  age?: number;
  house?: string;
  ustur?: string;
  note?: string;
};

/** Tensor.trade rank bands as used on the floor hunt (gold ≈ legendary). */
export function tensorTier(rank: number | null): TensorTier | "unknown" {
  if (rank == null) return "unknown";
  if (rank <= 5_000) return "anomaly";
  if (rank <= 80_000) return "legendary";
  if (rank <= 180_000) return "epic";
  if (rank <= 450_000) return "rare";
  if (rank <= 900_000) return "uncommon";
  return "common";
}

export function displayName(c: Crew) {
  return c.ustur ? `${c.given} ${c.ustur}` : `${c.given} ${c.family}`.trim();
}

export function hasApt(c: Crew, name: Aptitude, slot?: "major" | "minor") {
  return c.aptitudes.some((x) => x.name === name && (slot ? (slot === "major" ? x.xp === 50 : x.xp === 25) : true));
}

export function flyOk(c: Crew) {
  return hasApt(c, "Flight") && c.n <= 60 && c.c >= 30;
}

export function seats(c: Crew): string[] {
  const out: string[] = [];
  if (hasApt(c, "Command", "major")) out.push("капитан");
  else if (hasApt(c, "Command")) out.push("XO");
  if (hasApt(c, "Flight")) out.push(flyOk(c) ? "штурвал" : "не штурвал");
  if (hasApt(c, "Operator")) out.push("автоматика");
  if (hasApt(c, "Medical")) out.push("медик");
  if (hasApt(c, "Engineering")) out.push("инж");
  if (hasApt(c, "Hospitality")) out.push("камбуз");
  if (hasApt(c, "Science")) out.push("станция");
  if (hasApt(c, "Fitness") && !hasApt(c, "Flight")) out.push("пехота");
  return out;
}

export function mismatch(c: Crew) {
  const t = tensorTier(c.tensorRank);
  return c.official === "Common" && (t === "anomaly" || t === "legendary" || t === "epic");
}

export function xpSpread(c: Crew) {
  return c.aptitudes.reduce((s, a) => s + a.xp, 0);
}

